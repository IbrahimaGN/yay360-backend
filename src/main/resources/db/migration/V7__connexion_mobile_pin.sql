-- YAY360 — Connexion mobile : téléphone + code à usage unique (envoyé par e-mail) puis PIN à 4 chiffres,
-- avec session longue (« rester connecté ») par jeton de rafraîchissement à rotation.
-- Codes, PIN et jetons ne sont jamais stockés en clair (BCrypt pour le code et le PIN, SHA-256 pour les jetons).

ALTER TABLE utilisateurs ADD COLUMN IF NOT EXISTS pin varchar(100);
ALTER TABLE utilisateurs ADD COLUMN IF NOT EXISTS pin_echecs integer NOT NULL DEFAULT 0;
ALTER TABLE utilisateurs ADD COLUMN IF NOT EXISTS pin_verrouille_jusqua timestamp(6);
ALTER TABLE utilisateurs ADD COLUMN IF NOT EXISTS pin_verrouillages integer NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS codes_verification (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telephone             varchar(20)  NOT NULL,
    utilisateur_id        bigint REFERENCES utilisateurs (id) ON DELETE CASCADE,
    code_hache            varchar(100) NOT NULL,
    date_envoi            timestamp(6) NOT NULL,
    expiration            timestamp(6) NOT NULL,
    essais                integer      NOT NULL DEFAULT 0,
    utilise               boolean      NOT NULL DEFAULT false,
    -- Inscription en attente : le compte n'est créé qu'après vérification du code
    insc_nom              varchar(100),
    insc_prenom           varchar(100),
    insc_email            varchar(150),
    insc_date_naissance   date,
    jeton_pin_hache       varchar(64),
    jeton_pin_expiration  timestamp(6)
);
CREATE INDEX IF NOT EXISTS ix_codes_verification_telephone ON codes_verification (telephone, date_envoi);
CREATE INDEX IF NOT EXISTS ix_codes_verification_jeton_pin ON codes_verification (jeton_pin_hache);

CREATE TABLE IF NOT EXISTS jetons_rafraichissement (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id  bigint       NOT NULL REFERENCES utilisateurs (id) ON DELETE CASCADE,
    jeton_hache     varchar(64)  NOT NULL UNIQUE,
    famille         varchar(64)  NOT NULL,
    date_creation   timestamp(6) NOT NULL,
    expiration      timestamp(6) NOT NULL,
    revoque         boolean      NOT NULL DEFAULT false
);
CREATE INDEX IF NOT EXISTS ix_jetons_rafraichissement_famille ON jetons_rafraichissement (famille);
